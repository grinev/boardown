// Writes the kebab-case lucide names core validates and schema prints.
// Run after bumping lucide-react: `node scripts/generate-lucide-icon-names.mjs`.
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync } from 'node:fs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(resolve(root, 'packages/ui/package.json'));
const lucideMain = require.resolve('lucide-react');
const dts = resolve(dirname(lucideMain), '..', '..', 'dynamic.d.ts');
const text = readFileSync(dts, 'utf8');
const start = text.indexOf('declare const dynamicIconImports: {');
if (start === -1) throw new Error(`dynamicIconImports not found in ${dts}`);
const end = text.indexOf('\n};', start);
if (end === -1) throw new Error(`dynamicIconImports object did not close in ${dts}`);
const body = text.slice(start, end);
const names = [
  ...new Set(
    [...body.matchAll(/^\s+(?:'([^']+)'|([A-Za-z0-9-]+)):/gm)].map((m) => m[1] ?? m[2]),
  ),
].sort((a, b) => a.localeCompare(b));
if (names.length === 0) throw new Error('no icon names parsed');
for (const required of ['bug', 'bookmark', 'file-text', 'wrench', 'circle', 'server', 'trending-up']) {
  if (!names.includes(required)) throw new Error(`missing required icon name "${required}"`);
}

const lines = names.map((n) => `  ${JSON.stringify(n)},`).join('\n');
const out = `// Generated by scripts/generate-lucide-icon-names.mjs. Do not edit.
export const LUCIDE_ICON_NAMES: readonly string[] = [
${lines}
];

export const LUCIDE_ICON_NAME_SET: ReadonlySet<string> = new Set(LUCIDE_ICON_NAMES);
`;
const dest = resolve(root, 'packages/core/src/lucide-icon-names.ts');
writeFileSync(dest, out);
console.log(`  packages/core/src/lucide-icon-names.ts (${names.length} names)`);
